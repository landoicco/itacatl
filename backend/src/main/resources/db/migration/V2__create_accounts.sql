-- Accounts of the people who manage businesses: owners and staff. Customers have no account; they
-- verify a phone number instead (see docs/product-spec.md). See docs/security.md.

-- "user" is a reserved word in PostgreSQL
CREATE TABLE app_user (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- Stored lowercase, so sign-in ignores case and two accounts cannot differ only by case
    email VARCHAR(254) NOT NULL UNIQUE,
    -- Prefixed with its algorithm ({bcrypt}...), so the algorithm can change without a migration
    password_hash VARCHAR(255) NOT NULL,
    name VARCHAR(120) NOT NULL,
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_app_user_email CHECK (email = lower(email))
);

-- Which businesses a user works for, and as what. A table instead of a column on app_user, so one
-- person can run several businesses
CREATE TABLE membership (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    tenant_id BIGINT NOT NULL REFERENCES business (id) ON DELETE CASCADE,
    role VARCHAR(20) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_membership UNIQUE (user_id, tenant_id),
    CONSTRAINT ck_membership_role CHECK (role IN ('OWNER', 'STAFF'))
);

CREATE INDEX ix_membership_tenant ON membership (tenant_id);
