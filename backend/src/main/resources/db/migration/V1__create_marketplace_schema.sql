-- Marketplace schema: businesses (the tenants), their weekly schedule, their item catalog, and
-- the menus they publish for each service. See docs/domain-model.md.
--
-- Every table owned by a business carries tenant_id. Children reference their parent through
-- (id, tenant_id), so the database itself rejects a menu item that mixes two businesses.

CREATE TABLE business (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug VARCHAR(80) NOT NULL UNIQUE,
    name VARCHAR(120) NOT NULL,
    description TEXT,
    -- Schedules are local times; the zone turns them into instants
    time_zone VARCHAR(64) NOT NULL,
    accepts_pickup BOOLEAN NOT NULL DEFAULT TRUE,
    accepts_dine_in BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_business_slug CHECK (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
    CONSTRAINT ck_business_fulfillment CHECK (accepts_pickup OR accepts_dine_in)
);

-- Several rows per day allow split shifts (e.g. 8:00-12:00 and 17:00-21:00)
CREATE TABLE business_hours (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL REFERENCES business (id) ON DELETE CASCADE,
    -- ISO-8601: 1 = Monday ... 7 = Sunday, like java.time.DayOfWeek
    day_of_week SMALLINT NOT NULL,
    opens_at TIME NOT NULL,
    closes_at TIME NOT NULL,
    CONSTRAINT ck_business_hours_day CHECK (day_of_week BETWEEN 1 AND 7),
    -- No overnight windows yet: a service ends on the day it starts
    CONSTRAINT ck_business_hours_window CHECK (closes_at > opens_at)
);

CREATE INDEX ix_business_hours_tenant ON business_hours (tenant_id);

-- Replaces the weekly schedule on one date: closed all day, or special hours
CREATE TABLE schedule_exception (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL REFERENCES business (id) ON DELETE CASCADE,
    date DATE NOT NULL,
    -- Both NULL means closed all day
    opens_at TIME,
    closes_at TIME,
    CONSTRAINT uq_schedule_exception_date UNIQUE (tenant_id, date),
    CONSTRAINT ck_schedule_exception_window CHECK (
        (opens_at IS NULL AND closes_at IS NULL)
        OR (opens_at IS NOT NULL AND closes_at IS NOT NULL AND closes_at > opens_at)
    )
);

-- What a business knows how to make; offered in menus as menu items
CREATE TABLE item (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL REFERENCES business (id) ON DELETE CASCADE,
    name VARCHAR(120) NOT NULL,
    description TEXT,
    -- Prefilled when the item is added to a menu; the menu item's price is what is charged
    suggested_price NUMERIC(10, 2) NOT NULL,
    alcoholic BOOLEAN NOT NULL DEFAULT FALSE,
    -- Items are archived, never deleted, so past menus and orders keep their meaning
    archived BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_item_tenant UNIQUE (id, tenant_id),
    CONSTRAINT ck_item_price CHECK (suggested_price >= 0)
);

CREATE INDEX ix_item_tenant ON item (tenant_id);

-- What is sold in one service: a date and a local time window
CREATE TABLE menu (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL REFERENCES business (id) ON DELETE CASCADE,
    service_date DATE NOT NULL,
    starts_at TIME NOT NULL,
    ends_at TIME NOT NULL,
    status VARCHAR(20) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_menu_tenant UNIQUE (id, tenant_id),
    CONSTRAINT ck_menu_window CHECK (ends_at > starts_at),
    CONSTRAINT ck_menu_status CHECK (status IN ('DRAFT', 'PUBLISHED'))
);

CREATE INDEX ix_menu_tenant_date ON menu (tenant_id, service_date);

-- A catalog item offered in a menu, with that day's price and stock
CREATE TABLE menu_item (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL,
    menu_id BIGINT NOT NULL,
    item_id BIGINT NOT NULL,
    price NUMERIC(10, 2) NOT NULL,
    quantity INT NOT NULL,
    -- Optimistic locking for the stock holds that orders will take
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT fk_menu_item_menu FOREIGN KEY (menu_id, tenant_id)
        REFERENCES menu (id, tenant_id) ON DELETE CASCADE,
    -- No cascade: items are archived, never deleted. Checked at commit, because deleting a
    -- business cascades to its items and its menus in separate steps, and a check right after the
    -- items would still find the menu items that the menus' cascade is about to remove
    CONSTRAINT fk_menu_item_item FOREIGN KEY (item_id, tenant_id)
        REFERENCES item (id, tenant_id) DEFERRABLE INITIALLY DEFERRED,
    CONSTRAINT uq_menu_item UNIQUE (menu_id, item_id),
    CONSTRAINT ck_menu_item_price CHECK (price >= 0),
    CONSTRAINT ck_menu_item_quantity CHECK (quantity >= 0)
);

CREATE INDEX ix_menu_item_item ON menu_item (item_id, tenant_id);
